// The same article in the other language (for hreflang and the language switch).
export function counterpartSlug(slug, toLang) {
  const from = toLang === 'da' ? postsEn : postsDa;
  const to = toLang === 'da' ? postsDa : postsEn;
  const id = from.find((p) => p.slug === slug)?.id;
  return to.find((p) => p.id === id)?.slug || null;
}
